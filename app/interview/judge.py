# -*- coding: utf-8 -*-
"""Оцінювач: чи прозвучало у відповіді те, чого ми чекали.

Тут живуть **формулювання запитань до моделі** — і живуть окремо саме тому, що
їх міряють. `bin/judge_eval.py` імпортує ці самі функції й гоняє їх по еталону,
розміченому людиною (`tests/data/judge_cases.json`). Якщо промпт і мірка живуть
у двох копіях, вони розходяться, і число з мірки перестає щось означати.

⚠️ ГОЛОВНЕ, ЩО ТУТ ТРЕБА ЗНАТИ. На наборі, проти якого я підбирав формулювання,
виходило 82 % → 95 %. На **контрольному** наборі, написаному вже після
підбирання, усі формулювання дали однаково: 64-71 %, і найгірший сорт помилок
(`near` — відповідь поруч, але не та) лишився 1 із 3 у кожного.

    формулювання              підігнаний набір       контрольний набір
    «чи є це в тексті»        82 %, 6 хибних «так»    71 %, near 1/3
    «чи сказав саме це»       78 %, 3                 —
    «покажи цитату»           48 %, 20                —
    «перекажи, що сказано»    70 %, 12                —
    «чи можна дізнатися»      90 %, 1                 64 %, near 1/3
    те саме + критерій        95 %, 1                 71 %, near 1/3

Висновок, який дорого дався: **робота з формулюванням тут уперлась у стелю.**
Приріст на першому наборі був підгонкою під власний іспит. Тому не варто
крутити ці рядки далі в надії на диво — важелі лишились інші: сильніша модель
або можливість респондентові зняти хибну галочку (див. README).

Що все одно лишається правдою й чому формулювання саме таке: пункти гайда — це
**те, що ми хочемо дізнатися** («скільки вас було»), а не твердження, яке має
бути в тексті. Питання «чи сказав респондент саме це — «скільки вас було»?»
безглузде, і модель відповідала «ні» навіть на «Нас було шість людей».

Що НЕ спрацювало, хоч мало б (лишаю як застереження):
— цитата з перевіркою рядком. Ідея правильна — модель мусить показати, ДЕ вона
  це побачила, а ми звіряємо. Але 4B цитує завжди: 20 хибних «так» із 40.
  На сильнішій моделі варто спробувати ще раз;
— переказ із утечею «НЕ СКАЗАНО». Модель переказує будь-що й ніколи не
  визнає, що не сказано: 12 хибних «так».
"""

from typing import Optional


# ── формулювання ─────────────────────────────────────────────────────────

def item_question(answer: str, item: str, counts_if: str = "") -> str:
    """Чи можна дізнатися з відповіді конкретний пункт `must_learn`.

    `counts_if` — критерій зарахування з гайда: що конкретно мусить бути у
    відповіді. Без нього пункт лишається іменниковим ярликом («домовленість
    про витрати»), а ярлик ловить усе, що стоїть поруч у сенсі («грошей
    вистачило»). Критерій дає моделі те, чого в ярлику немає — перевірку.
    """
    head = (
        "ВІДПОВІДЬ РЕСПОНДЕНТА:\n%s\n\n"
        "Чи можна з цієї відповіді дізнатися: %s?\n\n" % (answer, item)
    )
    if not counts_if:
        # Гайд не дав критерію — віддаємо рівно те формулювання, яке дало 90 %
        # на основному наборі. Уточнення нижче я підбирав РАЗОМ із критеріями,
        # і без них вони роблять гірше: 75 % замість 90 %. Зміряно, не здогадка.
        return head + ("Якщо про це у відповіді нічого немає — «ні».\n"
                       "Відповідай ОДНИМ словом: так або ні.")
    return head + (
        "Зараховуй ЛИШЕ якщо у відповіді %s.\n"
        # Проти найгрубішої помилки: пункти виду «чи відкривали план» модель
        # читала як питання ДО СЕБЕ і відповідала «ні» на «в план не залазили»
        # — тобто на пряму відповідь респондента.
        "Ти оцінюєш НЕ те, як усе було, а те, чи є про це відповідь у тексті.\n"
        "Заперечна відповідь («не робили», «нічого не було») — це теж відповідь.\n"
        "Якщо цього у відповіді немає — «ні».\n"
        "Відповідай ОДНИМ словом: так або ні." % counts_if)


def topic_question(narrative: str, title: str, goal: str) -> str:
    """Чи згадав респондент тему у вільній розповіді.

    Тут «так» означає саме «згадав», а не «розповів вичерпно»: далі рушій
    відкриває таку тему питанням рівня 2 («до конкретики»), як і просить гайд
    для теми, згаданої побіжно. Тому й чекліст у фазі розповіді підписаний
    «Про що вже згадали», а не «Хочемо почути».
    """
    return (
        "РОЗПОВІДЬ РЕСПОНДЕНТА:\n%s\n\n"
        "Чи можна з цієї розповіді дізнатися: «%s» (%s)?\n\n"
        "Якщо про це у розповіді нічого немає — «ні».\n"
        "Відповідай ОДНИМ словом: так або ні." % (narrative, title, goal)
    )


SYSTEM = "Відповідай одним словом: так або ні."

# Схема для провайдерів зі структурованим виводом.
YES_NO_SCHEMA = {
    "type": "object",
    "properties": {"answer": {"type": "string", "enum": ["так", "ні"]}},
    "required": ["answer"],
    "additionalProperties": False,
}


def parse_yes_no(reply: str) -> bool:
    return (reply or "").strip().lower().lstrip("*_-• ").startswith("так")


def ask(llm, instruction: str) -> Optional[bool]:
    """Одне запитання до моделі. None — оцінити не вдалося.

    None і «ні» тут різні речі: «ні» лишає пункт відкритим свідомо, а None
    означає, що ми не знаємо, і вирішувати за цим не можна.
    """
    try:
        if getattr(llm, "supports_structured", True):
            data = llm.respond_json(
                system="Ти відповідаєш лише «так» або «ні».",
                messages=[{"role": "user", "content": instruction}],
                schema=YES_NO_SCHEMA,
            )
            return (data.get("answer") or "").strip().lower().startswith("так")
        return parse_yes_no(llm.respond_text(
            SYSTEM, [{"role": "user", "content": instruction}]))
    except Exception:
        return None
